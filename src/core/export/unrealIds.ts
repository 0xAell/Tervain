/** An id as a C++ constant’s name: wreck_blade becomes WreckBlade. */
export function cppIdentifier(id: string): string {
  const name = id.split(/[^A-Za-z0-9]+/).filter(Boolean).map((part) => part[0]!.toUpperCase() + part.slice(1)).join('');
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`The id "${id}" does not make a C++ name.`);
  return name;
}

const literal = (text: string) => {
  if (!/^[A-Za-z0-9_.\- ]+$/.test(text)) throw new Error(`The id "${text}" needs escaping to be a C++ string.`);
  return `TEXT("${text}")`;
};

export function unrealIdsHeader(groups: readonly UnrealIdGroup[] = unrealIdGroups(), constants: readonly UnrealIdConstant[] = unrealIdConstants()): string {
  const out: string[] = [
    '// Generated by `npm run data:export` from src/core/export/unrealIds.ts. Do not edit: change the core and export',
    '// again. `npm run unreal:check` fails, here and in CI, when this file and the core disagree.',
    '',
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '',
    '/**',
    ' * The ids the core gives its things, for C++ that has to name one: FName(TervainIds::Item::Bread).',
    ' * A group that names a table holds the row names of that DataTable. The groups of the quest are the values saved',
    ' * games and dialogue conditions use (data/game/quest.json).',
    ' */',
    'namespace TervainIds',
    '{',
  ];
  for (const group of groups) {
    const names = group.ids.map(cppIdentifier);
    const repeated = names.find((name, index) => names.indexOf(name) !== index || name === 'All');
    if (repeated) throw new Error(`${group.name}: two ids make the C++ name ${repeated}.`);
    out.push(`\t/** ${group.note}${group.table ? ` Row names of ${group.table.replace(/\.json$/, '')}.` : ''} */`, `\tnamespace ${group.name}`, '\t{');
    group.ids.forEach((id, index) => out.push(`\t\tinline constexpr const TCHAR* ${names[index]} = ${literal(id)};`));
    out.push('', '\t\t/** All of them, in the order the core keeps them. */', '\t\tinline constexpr const TCHAR* All[] = {');
    for (let at = 0; at < names.length; at += 6) out.push(`\t\t\t${names.slice(at, at + 6).join(', ')},`);
    out.push('\t\t};', '\t}', '');
  }
  for (const constant of constants) {
    out.push(`\t/** ${constant.note} */`, typeof constant.value === 'number'
      ? `\tinline constexpr int32 ${constant.name} = ${constant.value};`
      : `\tinline constexpr const TCHAR* ${constant.name} = ${literal(constant.value)};`, '');
  }
  out.pop();
  out.push('}', '');
  const text = out.join('\n');
  // Plain ASCII, so the header compiles the same whatever code page a compiler assumes.
  const odd = /[^\x09\x0a\x20-\x7e]/.exec(text);
  if (odd) throw new Error(`The ids header would hold a character outside ASCII: ${JSON.stringify(odd[0])}.`);
  return text;
}
