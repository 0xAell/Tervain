import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { VOICE_LINES } from '../../src/core/content/voice';
import { VOICE_LINE_SECONDS } from '../../src/core/content/voiceLengths';
import { VOICE_AUDIO } from '../../src/presentation/sound/voiceManifest';

// The core books exchanges and overheard scenes for the length of their lines, so it keeps how long each recorded line
// lasts (src/core/content/voiceLengths.ts), and the export carries it. Here that table is held to the recordings, as
// the audio tools list them; if the two part, regenerate it with
//   VOICE_LENGTHS_WRITE=1 npx vitest run --project game tests/presentation/voiceLengths.test.ts

const target = new URL('../../src/core/content/voiceLengths.ts', import.meta.url);

describe('how long each spoken line lasts', () => {
  it('is the length of its recording, for every recorded line and no other', () => {
    const recorded = Object.fromEntries(Object.entries(VOICE_AUDIO.lines as Record<string, readonly [string, number, number, string]>).map(([id, [, , seconds]]) => [id, seconds]));
    if (process.env.VOICE_LENGTHS_WRITE) {
      const ids = Object.keys(recorded).sort();
      writeFileSync(target, [
        '// Generated by tests/presentation/voiceLengths.test.ts from src/presentation/sound/voiceManifest.ts, the voice manifest',
        '// the audio tools write. Do not edit by hand: the test fails if this and the recordings part. Regenerate it with',
        '//   VOICE_LENGTHS_WRITE=1 npx vitest run --project game tests/presentation/voiceLengths.test.ts',
        '',
        '/** How long each spoken line lasts as recorded (s). A line with no recording is shown and not heard. */',
        'export const VOICE_LINE_SECONDS: Readonly<Record<string, number>> = {',
        ...ids.map((id) => `  ${JSON.stringify(id)}: ${recorded[id]},`),
        '};',
        '',
      ].join('\n'));
    }
    expect(VOICE_LINE_SECONDS).toEqual(recorded);
    // Every recorded line is one the game speaks.
    for (const id of Object.keys(VOICE_LINE_SECONDS)) expect(VOICE_LINES[id], id).toBeDefined();
  });
});
