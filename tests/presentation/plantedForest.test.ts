// Tree identities, planar positions and gameplay footprints belong to the saved world. Replacing art must preserve them.
// Recompute the seats of the redesigned woodland families, navigation clearance and ground cover from the real models.
// PLANTED_FOREST_WRITE=1 npx vitest run --project game tests/presentation/plantedForest.test.ts

const fixed = (value: number, places: number) => Math.round(value * 10 ** places) / 10 ** places;
const forestFile = new URL('../../src/core/world/plantedForest.trees.ts', import.meta.url);
const floorFile = new URL('../../src/core/world/plantedForest.floor.ts', import.meta.url);
const modelsFile = new URL('../../src/core/world/plantedForest.models.ts', import.meta.url);

// JSON writes a number as the shortest decimal that reads back as the same double, so the rows are the planting to the
// bit; only a negative zero needs saying.
const cell = (value: unknown) => Object.is(value, -0) ? '-0' : JSON.stringify(value);

function renderModels(plantedWith: string, draws: readonly string[]): string {
  return [
    '// Generated by tests/presentation/plantedForest.test.ts from the shipped tree models. Do not edit by hand.',
    '// A module of its own: the menu reads it to fetch a journey\'s trees ahead, without the planting\'s rows.',
    '',
    '/** What the web build plants its forest with by default, as presentation/forestPlanting.ts names it (forestPlantingKey). */',
    `export const PLANTED_WITH = ${JSON.stringify(plantedWith)};`,
    '',
    '/** The tree models the planted forest is drawn with (meshyTrees.ts ids): all a journey that takes it loads (forestTreeIds). */',
    `export const PLANTED_DRAWS: readonly string[] = [${draws.map((id) => JSON.stringify(id)).join(', ')}];`,
    '',
  ].join('\n');
}

function renderForest(rows: readonly PlantedRow[]): string {
  const line = (row: PlantedRow) => {
    const cells: unknown[] = [...row];
    while (cells.length > 13 && cells[cells.length - 1] === null) cells.pop();
    return `  [${cells.map(cell).join(', ')}],`;
  };
  return [
    '// Generated by tests/presentation/plantedForest.test.ts from the shipped tree models. Do not edit by hand.',
    "import type { Species, TreeAge } from './flora';",
    "import type { ForestFamilyRole } from './forestStands';",
    '',
    '/**',
    ' * Each tree as the web build plants it, to the bit: species, variant, x, y, z, scale, yaw, tint, radius as an obstacle (m),',
    ' * collision id, decoration rank, the radius its drawn wood keeps the walk grid clear of (m; 0 for a tree that does not',
    ' * block), and its age, grove, stand, role in the stand and supplied model where it has them.',
    ' */',
    'export type PlantedRow = readonly [sp: Species, v: number, x: number, y: number, z: number, s: number, yaw: number, tint: number, radius: number,',
    '  collisionId: string | null, decorationRank: number, navigationRadius: number, age: TreeAge | null, groveId?: string | null, standId?: string | null,',
    '  familyRole?: ForestFamilyRole | null, assetId?: string | null];',
    '',
    'export const PLANTED_ROWS: readonly PlantedRow[] = [',
    ...rows.map(line),
    '];',
    '',
  ].join('\n');
}

function renderFloor(pieces: readonly ForestFloorPiece[]): string {
  const line = (p: ForestFloorPiece) => `  [${JSON.stringify(p.id)}, ${JSON.stringify(p.kind)}, ${p.x}, ${p.y}, ${p.z}, ${p.nx}, ${p.nz}, ${p.yaw}, ${p.scale}, ${p.rank}, ${p.variant}${p.colonyId || p.parentLogId ? `, ${JSON.stringify(p.colonyId ?? null)}` : ''}${p.parentLogId ? `, ${JSON.stringify(p.parentLogId)}` : ''}],`;
  return [
    '// Generated by tests/presentation/plantedForest.test.ts from the shipped tree models. Do not edit by hand.',
    "import type { ForestFloorKind } from './forestFloor';",
    '',
    '/** Id, kind, x, y, z, the ground normal\'s x and z, yaw, scale, detail rank, variant, and the colony and the log it lies on, if any. */',
    'export type FloorRow = readonly [id: string, kind: ForestFloorKind, x: number, y: number, z: number, nx: number, nz: number, yaw: number, scale: number, rank: number, variant: number, colonyId?: string | null, parentLogId?: string];',
    '',
    'export const FLOOR_ROWS: readonly FloorRow[] = [',
    ...pieces.map(line),
    '];',
    '',
  ].join('\n');
}

describe('the forest the core exports', () => {
  let meshy: MeshyForest, pine: PineForest, hero: HeroPineForest | null, models: ForestModels, terrain: Terrain, population: FloraTree[];
  beforeAll(async () => {
    const [meshySource, pineSource, heroSource] = await Promise.all([meshyTreeTemplates(activeMeshyTreeIds()), pineTemplates(), HERO_PINE_DEFAULT ? heroPineFixtureTemplates() : null]);
    meshy = createMeshyForest(meshySource); pine = createPineForest(pineSource); hero = heroSource ? createHeroPineForest(heroSource) : null;
    terrain = new Terrain(); models = forestModels(pine, meshy, hero);
    population = PLANTED_FLORA.map(original => {
      const tree = { ...original };
      if (['fir', 'shorepine', 'palm'].includes(tree.sp) || tree.assetId === 'tree-1505') {
        const variant = models.variantFor(tree), plane = groundedTreeY(terrain, tree, variant);
        tree.y = groundedTreeFlareY(terrain, tree, variant, plane);
      }
      return tree;
    });
  }, 600_000);
  afterAll(() => { meshy?.dispose(); pine?.dispose(); hero?.dispose(); });

  it('preserves the original save-compatible woodland layout and measures navigation from the current meshes', () => {
    const identity = population.map(t => [t.sp, t.v, t.x, t.z, t.s, t.yaw, t.radius, t.collisionId, t.groveId, t.standId]);
    expect(createHash('sha256').update(JSON.stringify(identity)).digest('hex')).toBe('e6fc2543f699927fddadc2df6c74a0166a732cda43270e68e7d56a610e6de47c');
    // As registerFloraColliders makes them: only a tree with an id and a footprint blocks, at its footprint, and the walk grid
    // keeps clear of the drawn wood where that reaches further.
    const planted = population.map((tree): PlantedTree => {
      const blocks = !!tree.collisionId && tree.radius > 0;
      return {
        sp: tree.sp, v: tree.v, x: fixed(tree.x, 4), y: fixed(tree.y, 4), z: fixed(tree.z, 4), s: fixed(tree.s, 5), yaw: fixed(tree.yaw, 5),
        radius: blocks ? fixed(tree.radius, 4) : 0, navigationRadius: blocks ? fixed(Math.max(tree.radius, plantedObstacleRadius(terrain, models, tree)), 4) : 0,
        ...(tree.assetId ? { assetId: tree.assetId } : {}),
      };
    });
    const rows = population.map((tree): PlantedRow => [tree.sp, tree.v, tree.x, tree.y, tree.z, tree.s, tree.yaw, tree.tint, tree.radius,
      tree.collisionId, tree.decorationRank, tree.collisionId && tree.radius > 0 ? plantedObstacleRadius(terrain, models, tree) : 0, tree.age ?? null,
      tree.groveId ?? null, tree.standId ?? null, tree.familyRole ?? null, tree.assetId ?? null]);
    // What the web build plants with by default (no flag), and the models its trees are drawn with: a journey that takes
    // this forest loads only those. The planting runs here in node, where the leaf atlas never loads: with the atlas on
    // by default, the copy would be planted without it and the browser with it.
    expect(LEAF_ATLAS_DEFAULT).toBe(false);
    const plantedWith = forestPlantingKey(!!hero, '');
    const draws = [...new Set(population.filter((tree) => !models.usesPine(tree.sp)).map((tree) => models.variantFor(tree).assetId!))].sort();
    if (process.env.PLANTED_FOREST_WRITE) { writeFileSync(forestFile, renderForest(rows)); writeFileSync(modelsFile, renderModels(plantedWith, draws)); }
    expect(PLANTED_WITH).toBe(plantedWith);
    expect(PLANTED_DRAWS).toEqual(draws);
    // The game takes these trees as they are when it plants with those (buildFlora): every field, to the bit.
    expect(PLANTED_FLORA).toEqual(population);
    expect(PLANTED_FLORA.every((tree, i) => Object.entries(tree).every(([key, value]) => Object.is(value, population[i]![key as keyof typeof tree])))).toBe(true);
    // The export's view rounds them as above.
    expect(PLANTED_FOREST).toEqual(planted);
    // Fewer than the places the rule offers with the supplied trees' footprints: the drawn models are wider.
    const offered = createFloraPopulation(terrain, new Exclusions(terrain));
    expect(PLANTED_FOREST.length).toBeLessThan(offered.length);
  });

  it('is the woodland floor the game lays among those trees, piece for piece', () => {
    // As buildFlora gathers them: the near crowns of the trees that stand in the way are the shade the floor's rule reads.
    const crowns = new PlantedCrownIndex();
    for (const tree of population) {
      if (!tree.collisionId) continue;
      const leaf = models.variantFor(tree).lods[0].leaf;
      if (leaf) crowns.add(tree.sp, tree, leaf);
    }
    const laid = createForestFloorPopulation(terrain, new Exclusions(terrain), population, crowns).map((piece): ForestFloorPiece => ({
      id: piece.id, kind: piece.kind, x: fixed(piece.x, 6), y: fixed(piece.y, 6), z: fixed(piece.z, 6), nx: fixed(piece.nx, 6), nz: fixed(piece.nz, 6),
      yaw: fixed(piece.yaw, 6), scale: fixed(piece.scale, 6), rank: fixed(piece.rank, 6), variant: piece.variant,
      ...(piece.colonyId ? { colonyId: piece.colonyId } : {}), ...(piece.parentLogId ? { parentLogId: piece.parentLogId } : {}),
    }));
    if (process.env.PLANTED_FOREST_WRITE) writeFileSync(floorFile, renderFloor(laid));
    expect(PLANTED_FLOOR).toEqual(laid);
    // More than the rule lays when it estimates the shade from the trees' sizes alone.
    expect(PLANTED_FLOOR.length).toBeGreaterThan(createForestFloorPopulation(terrain, new Exclusions(terrain), population).length);
  });
});
